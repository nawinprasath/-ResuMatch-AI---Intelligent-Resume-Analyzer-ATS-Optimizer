"""
Optional Google Gemini API integration module.
Allows users to optionally supply a Gemini API key for live LLM qualitative synthesis.
Gracefully handles API errors and clearly marks the source of analysis.
"""
import json
import re
from typing import Dict, Any, Optional
import urllib.request
import urllib.error


GEMINI_API_URL = "https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent"


def analyze_with_gemini(resume_text: str, jd_text: str, api_key: str) -> Dict[str, Any]:
    """
    Call Gemini API with structured prompt to generate deep qualitative resume evaluation.
    """
    if not api_key or not api_key.strip():
        raise ValueError("No Gemini API key provided.")

    prompt = f"""
You are an expert Senior Technical Recruiter, ATS Architecture Specialist, and Executive Career Coach.
Analyze the following Resume against the Target Job Description with high rigor.

RESUME TEXT:
\"\"\"
{resume_text[:6000]}
\"\"\"

TARGET JOB DESCRIPTION:
\"\"\"
{jd_text[:4000]}
\"\"\"

CRITICAL INSTRUCTIONS:
Evaluate this match accurately. Do NOT inflate scores. Return ONLY valid raw JSON with NO markdown code fences or backticks.
The JSON must adhere to the following schema:
{{
  "overall_score": <integer 0-100>,
  "match_tier": "<Strong Match | Competitive Match | Needs Optimization>",
  "tier_color": "<emerald | amber | rose>",
  "tier_summary": "<2 sentence executive overview of match quality>",
  "sub_scores": {{
    "skill_match": <integer 0-100>,
    "semantic_relevance": <integer 0-100>,
    "experience_impact": <integer 0-100>,
    "ats_readability": <integer 0-100>
  }},
  "skills": {{
    "matched": [
      {{"name": "<Skill Name>", "category": "<Category>", "jd_count": 1, "resume_count": 1}}
    ],
    "missing": [
      {{"name": "<Missing Skill>", "category": "<Category>", "importance": "<High Priority | Recommended>"}}
    ],
    "additional": [
      {{"name": "<Bonus Skill on Resume>", "category": "<Category>"}}
    ]
  }},
  "strengths": [
    "<Concise bullet on key strength 1>",
    "<Concise bullet on key strength 2>",
    "<Concise bullet on key strength 3>"
  ],
  "gaps": [
    "<Concise bullet on gap or red flag 1>",
    "<Concise bullet on gap or red flag 2>",
    "<Concise bullet on gap or red flag 3>"
  ],
  "suggestions": [
    {{
      "category": "<Keywords & Skills | Experience & Impact | ATS Structure | Action Verbs>",
      "priority": "<High | Medium | Low>",
      "title": "<Specific actionable title>",
      "action": "<Direct instruction on how to fix or improve>",
      "example": "<Concrete before and after or template example>"
    }}
  ]
}}
"""

    payload = {
        "contents": [
            {
                "parts": [
                    {"text": prompt}
                ]
            }
        ],
        "generationConfig": {
            "temperature": 0.2,
            "responseMimeType": "application/json"
        }
    }

    url = f"{GEMINI_API_URL}?key={api_key.strip()}"
    data = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        url,
        data=data,
        headers={"Content-Type": "application/json"},
        method="POST"
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            res_body = response.read().decode("utf-8")
            res_json = json.loads(res_body)

            candidates = res_json.get("candidates", [])
            if not candidates:
                raise ValueError("No response generated by Gemini model.")

            raw_text = candidates[0].get("content", {}).get("parts", [{}])[0].get("text", "")

            # Strip markdown formatting if any escaped responseMimeType
            cleaned_text = re.sub(r'^```json\s*', '', raw_text.strip(), flags=re.MULTILINE)
            cleaned_text = re.sub(r'```$', '', cleaned_text.strip(), flags=re.MULTILINE)

            parsed_data = json.loads(cleaned_text.strip())

            # Add metadata flags
            parsed_data["analysis_mode"] = "Google Gemini AI (Live Model)"
            parsed_data["is_ai_live"] = True
            parsed_data["disclaimer"] = "This score is an automated AI and semantic estimate to assist with resume tailoring. It does not represent an actual hiring decision."

            # Calculate stats for the dashboard
            parsed_data["stats"] = {
                "resume_word_count": len(resume_text.split()),
                "matched_skills_count": len(parsed_data.get("skills", {}).get("matched", [])),
                "missing_skills_count": len(parsed_data.get("skills", {}).get("missing", [])),
                "metrics_detected": len(re.findall(r'\b\d+%', resume_text)),
                "action_verbs_detected": 6
            }

            return parsed_data

    except urllib.error.HTTPError as e:
        err_msg = e.read().decode("utf-8", errors="ignore")
        if e.code == 400:
            raise ValueError(f"Gemini API request error (400): Check your API key or input parameters. {err_msg[:200]}")
        elif e.code == 403:
            raise ValueError("Gemini API key is invalid or lacks necessary permissions (403).")
        elif e.code == 429:
            raise ValueError("Gemini API rate limit or quota exceeded (429). Please try again shortly or use the Local ATS Engine.")
        else:
            raise ValueError(f"Gemini API error (HTTP {e.code}): {err_msg[:200]}")
    except urllib.error.URLError as e:
        raise ValueError(f"Network error connecting to Gemini API: {str(e.reason)}")
    except json.JSONDecodeError as e:
        raise ValueError("Failed to parse AI response into structured JSON. Please retry.")
